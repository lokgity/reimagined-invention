# 加盟费的**三态**（2026-09-18 新增，瑞幸入表时暴露的缺口）
#   'amount'  —— 有公开口径的加盟费金额
#   'none'    —— **明确不收加盟费**（fee = 0，且这个 0 是事实）
#   'unknown' —— 公开口径查不到或分歧过大 → fee = None
#
# ⚠️ 为什么必须有第三态：旧代码用 `if fee:` 判分支，把 0 与 None 混成同一结果 ——
#   对"查不到"它是安全的（显示"暂无公开口径"），但对"明确不收"它说的是**假话**
#   （瑞幸被显示成"暂无公开加盟费口径"，而瑞幸的 0 加盟费恰恰是它最出名的公开政策）。
#   ⚠️ 反向也成立：**"查不到"绝不许写成 0** —— 那会把"不知道"伪装成"免费"，
#   下限校验从此永不触发（旧门禁 §14 就是钉这一条的）。
_JOIN_FEE_NONE = {'瑞幸'}


def join_fee_status(brand: str) -> str:
    """加盟费三态：'amount' / 'none' / 'unknown'。未知品牌 → 'unknown'。"""
    if not brand:
        return 'unknown'
    if brand in _JOIN_FEE_NONE:
        return 'none'
    fee = _JOIN_FEE.get(brand, (None,))[0]
    return 'amount' if fee else 'unknown'


def get_franchise_info(brand: str):
    """取品牌加盟政策参考; 无该品牌或自创品牌返回 None。

    返回值在 invest_ref / yearly_fee 之外，**额外带加盟费单列字段**（2026-09-17）：
      join_fee      : 单列加盟费（元）；**None = 公开口径不可得**
      join_fee_unit : '元/年' / '元/首年' / '元/授权期' / '元'
      join_fee_band : (下限, 上限) 或 None
      join_fee_tier : 'B' 财经媒体/官方口径 ｜ 'C' 仅第三方招商站 ｜ '' 无
      join_fee_src  : 来源说明（UI 原样转达，不许加工成"官方"）
      join_fee_status: 'amount' / 'none'（明确不收）/ 'unknown'（查不到）—— 2026-09-18

    ⚠️ `join_fee is None` 必须区别对待：
       它是"**没查到**"，不是"不收加盟费"。调用方要跳过下限校验并如实说明，
       不能拿 0 去比 —— 那会把"不知道"伪装成"免费"。
    ⚠️ `join_fee == 0` 且 `join_fee_status == 'none'` 是**另一回事**：
       它是"**明确不收**"，同样是跳过下限校验，但**文案必须说"明确不收"**，
       不能说"暂无公开口径" —— 后者对瑞幸是假话。
    """
    if not brand:
        return None
    info = FRANCHISE_INFO.get(brand)
    if not info:
        return None
    out = dict(info)
    jf, unit, lo, hi, tier, src = _JOIN_FEE.get(brand, (None, '', None, None, '', ''))
    status = join_fee_status(brand)
    out.update({
        'join_fee': jf,
        'join_fee_unit': unit,
        'join_fee_band': (lo, hi) if lo else None,
        'join_fee_tier': tier,
        'join_fee_src': src,
        'join_fee_status': status,
        # 该品牌特有的、**必须随结论一起说出口**的成本/资质提示（可为空）
        # 2026-09-18 新增，起因：瑞幸的"毛利阶梯分成"不进 月成本合计，
        # 若不出声明就等于静默给了一份偏乐观的结论。
        'cost_notes': list(info.get('cost_notes') or []),
    })
    return out


def get_join_fee(brand: str):
    """只要加盟费门槛（给 UI 做提示与下限校验用）。

    返回 dict（含 fee/unit/band/tier/src/text），品牌无公开口径时 fee=None。
    `text` 是**可直接显示的一行**，避免 UI 各处自己拼、拼出不一致的措辞。
    """
    info = get_franchise_info(brand)
    if not info:
        return None
    fee = info.get('join_fee')
    unit = info.get('join_fee_unit') or ''
    band = info.get('join_fee_band')
    tier = info.get('join_fee_tier') or ''
    status = info.get('join_fee_status') or 'unknown'
    if status == 'none':
        # 明确不收：这句话是**事实陈述**，不是"没查到"。且必须把"分成"这条附带成本
        # 说出来 —— 否则用户会以为"0 加盟费 = 品牌方不抽成"。
        text = ('该品牌**明确不收加盟费**（新零售合伙人联营模式）→ 加盟费下限校验不适用；'
                '品牌方收益来自**门店月毛利的阶梯分成**（联营模式的品牌方成本，'
                '本项目暂未计入成本测算，见已知局限）')
        text += f"｜截至 {_JOIN_FEE_ASOF} 核实"
    elif fee:
        text = f"加盟费 ¥{fee:,} {unit}".strip()
        if band and band[0] != band[1]:
            text += f"（公开口径区间 ¥{band[0]:,}~¥{band[1]:,}）"
        text += f"｜截至 {_JOIN_FEE_ASOF} 核实"
        if tier == 'C':
            text += "〔第三方招商口径，非官方披露，请与品牌方核对〕"
    else:
        text = '该品牌**暂无公开加盟费口径**（不编数据）→ 不做下限校验'
    return {'brand': brand, 'fee': fee, 'unit': unit, 'band': band,
            'tier': tier, 'status': status, 'src': info.get('join_fee_src') or '',
            'asof': _JOIN_FEE_ASOF, 'text': text}


def brand_attractiveness(name: str):
    """从店名识别品牌引力系数。
    返回 (品牌名或None, S)。识别不出 → (None, DEFAULT_S)。"""
    if not name:
        return None, DEFAULT_S
    for brand, kws in BRAND_KEYWORDS.items():
        for kw in kws:
            if kw in name:
                return brand, BRAND_S.get(brand, DEFAULT_S)
    return None, DEFAULT_S


def supported_brands():
    return sorted(BRAND_S.keys())


