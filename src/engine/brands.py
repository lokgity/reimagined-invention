# 用户选择"不加盟/自己起名"时 state['brand'] 的取值 → 归入"个体/杂牌"标定档
# 注意：这是**用户明确的选择**，不是"识别不出的未知品牌"，
#       所以 strict=True 时也要给出 uplift（区别于错别字品牌）
_SELF_BRAND_ALIASES = {'自创品牌', '个体/杂牌', '个体', '杂牌', '不加盟', '自营'}


def is_self_brand(name_or_brand) -> bool:
    """用户是否**明确选择**了"自创品牌 / 不加盟 / 个体经营"。

    必须与"识别不出的未知品牌"区分开：
      - 自创品牌：是用户的决策，按"个体/杂牌"档标定（有 uplift）；
      - 错别字/未收录品牌：识别不出，不宜硬套任何档位（strict 下保持中性）。
    同时，自创品牌**不存在"同品牌连锁门店"**，因此客单价校正这一步
    在定义上就不适用，不该去查、也不该报成"附近没抓到"。
    """
    return bool(name_or_brand) and str(name_or_brand).strip() in _SELF_BRAND_ALIASES


def brand_uplift(name_or_brand, strict=False):
    """返回品牌相对溢价系数。

    name_or_brand: 门店全名（如 '蜜雪冰城(天一广场店)'）或纯品牌名。
    strict: False（默认，用于**竞品/已存在门店**）
              — 识别不出连锁 → 视为个体杂牌，返回其 uplift (0.8370, v6)。
             这是 POI 店名的现实：街边独立奶茶店本就该按杂牌处理。
            True（用于**候选/待评估品牌**）
              — 识别不出 → 返回 (None, 1.0)，不给任何溢价。
             用于用户输入的品牌名，避免把错别字/未知品牌误加成杂牌溢价。

    返回: (品牌名 or None, uplift 系数)。空输入 → (None, 1.0)。
    """
    if not name_or_brand:
        return None, 1.0
    s = str(name_or_brand).strip()
    if s in UPLIFT:
        return s, UPLIFT[s]
    # 用户明确选了"自创品牌/不加盟" → 就是标定里的"个体/杂牌"那一档，
    # 不是"未知品牌"。strict 模式下也要认，否则卡片承诺的 +6% 落不了地。
    if s in _SELF_BRAND_ALIASES:
        return '个体/杂牌', UPLIFT.get('个体/杂牌', 1.0)
    brand, _ = brand_attractiveness(s)
    if brand:
        return brand, UPLIFT.get(brand, 1.0)
    if strict:
        # 未知品牌：不猜成杂牌，保持中性
        return None, 1.0
    # 店名里完全识别不出连锁品牌 → 按个体杂牌处理
    return '个体/杂牌', UPLIFT.get('个体/杂牌', 1.0)


def brand_uplift_detail(name_or_brand, strict=False):
    """同 brand_uplift，但额外返回可靠性信息，供报告/UI 标注。

    返回 dict:
      brand : 品牌名 or None
      uplift: 系数
      tier  : 'TIER1'(可信) / 'TIER2'(参考) / 'TIER3'(未收录, 取1.0)
      ci    : (lo, hi) bootstrap 95% 区间, 未收录为 None
      n     : 标定样本量, 未收录为 None
    """
    brand, up = brand_uplift(name_or_brand, strict=strict)
    if brand is None:
        return dict(brand=None, uplift=1.0, tier='TIER3', ci=None, n=None)
    if brand not in UPLIFT:
        # 识别出品牌但未收录（n<3，收缩后≈1.0）
        return dict(brand=brand, uplift=1.0, tier='TIER3', ci=None, n=None)
    return dict(
        brand=brand, uplift=up,
        tier=UPLIFT_TIER.get(brand, 'TIER2'),
        ci=UPLIFT_CI.get(brand), n=_UPLIFT_N.get(brand),
    )


