"""
brands.py —— 品牌引力系数表（真 Huff 模型的 S 项）
=====================================================
真 Huff 捕获份额: P_j = (S_j/d^λ) / Σ_k(S_k/d_k^λ)
其中 S 是"商店吸引力"。对茶饮品类, S 的主要可观测代理是品牌势能。

系数标定依据（答辩口径）:
- 分档锚定: 窄门餐眼 2026 全国门店数量级（3万+/万店级/数千家/数百家/个体）
- 实证校验: 三商圈 83 家真实门店, 同商场内（控制位置变量）
  品牌系数 vs 外卖月售 Spearman = 0.414（海宁银泰），方向与量级成立
- 用途边界: 仅用于"相对竞争力"排序, 不代表真实流水倍数

当前覆盖: 奶茶/茶饮品类（约 30 品牌）。其他品类品牌识别命中率低,
引擎自动退化为 S=1.0（纯距离 Huff），行为与旧版一致。

品牌相对溢价 UPLIFT（品牌盲残差口径，v7 整改）
------------------------------------------------------------------
为什么需要: 实测 D×P 的方差 69.5% 由**商圈**解释, 品牌仅 8.0%
（R²: 仅商圈2参数=0.6946 vs 仅品牌9参数=0.0795）。同品牌跨商圈极差达
4~4.6 倍（蜜雪 4.58x / 沪上阿姨 4.61x / CoCo 4.02x）。
因此"按品牌给锚点"不可辨识——那实质是"按商圈给锚点", 换城市即失效。

做法: 在**同商圈内部**做品牌比较, 剔除商圈混淆:
    uplift_b = median( DP_blind_store / DP_blind_median(该店所在商圈) )
其中 **DP_blind 用"品牌盲"重算**（把自己那项的 own_S 置 1.0, 竞品 S 保持真实）,
再向 1.0 收缩: uplift = 1 + w·(raw − 1),  w = n/(n+K), K=5。

⚠️⚠️ 为什么必须"品牌盲"（v6 的双算, 2026-09-18 整改）
   旧口径直接比 DP_store/同商圈中位DP。而 P 的分子是 own_S、分母是周边竞品
   （与自己品牌无关）⇒ 同一点位上 P 是 own_S 的单调函数 ⇒ 旧 uplift 在
   **重复表达 own_S**。而流水估算里 own_S 已通过 P 计入过一次（scoring.py:701),
   `brand_factor`(=uplift) 又在 scoring.py:331 乘一次 = **双算**。
   实测（recalibrate_uplift_v3.py §2）：Spearman(own_S, uplift_raw) 从
   v6 的 **+0.6719** 降到 v7 的 **+0.1531**；个体/杂牌 0.8370→1.0111、
   蜜雪 1.1903→1.0018 —— v6 那些"溢价"绝大部分就是 own_S 自己。
   v7 的残差度量的是**位置/竞争微区位**（"假设这家店没有品牌力, 它还比同商圈
   中位店好多少"），与 own_S 正交, 因此不再双算。

⚠️ 用途边界: uplift 只用于**流水估算的品牌水平修正**,
   不进入 Huff 结构（λ、d0 不变）, 也不用于竞争分排序。
   样本: 全库 3959 条奶茶 POI → 锚定 3563 家 → 采用 1631 家 / 28 品牌。
"""

