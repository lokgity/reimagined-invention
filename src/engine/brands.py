# 品牌级门店经营数据（公开披露，可溯源）
# ===============================================================
# ⚠️ 为什么要有这一段（2026-09-15 发现并修正的单位错误）
#
# 高德 biz_ext.cost 的官方定义是「人均消费」。但在茶饮类目**实测值 ≈ 单杯价**，
# 不是「每单金额」。三重对照（详见 docs/品牌级公开数据与客单价口径修正.md）：
#   蜜雪冰城  高德 ¥7.0  |  招股书单杯 ¥6.72  |  招股书每单 ¥11.4
#   沪上阿姨  高德 ¥14.0 |  价格带 7~22 中位 |  招股书每单 ¥25
#   霸王茶姬  高德 ¥20.0 |  招股书单杯 ¥20.48|  招股书自述客单 16~20
#
# 而引擎公式是  月流水 = 日订单量 × 每单金额 ，
# 其中 daily_sales=250 明确是**日订单量**（83 家中位门店参考）。
# 把「单杯价」直接当「每单金额」乘进去 = 少算约 1.7 倍（一单约 1.7 杯），
# 会让低价品牌全线显示亏损、回本周期翻倍，**结论方向都是错的**。
#
# 正确口径：每单金额 = 公开披露的「每单平均零售额」，缺失时用「单杯价 × 每单杯数」。
# ---------------------------------------------------------------
# 每单杯数（单杯价 → 每单金额 的换算系数）
#   蜜雪冰城  11.4 元/单 ÷ 6.72 元/杯 = 1.70
#   沪上阿姨  25.0 元/单 ÷ ~14 元/杯  = 1.79
# 两点均值 1.74，取保守整值 1.7。
# ⚠️ 这不是常数：高端品牌一单往往就是一杯（霸王茶姬客单 16~20 与单杯
#   ¥20.48 几乎相等 → ≈1.0 杯/单），因此换算对高价品牌可能高估。
#   该不确定性由 scoring 的「口径区间」以 [1.0, 1.8] 两端呈现。
UNIT_PER_ORDER = 1.7

# 口径区间的换算系数两端（1.0 = 一单一杯，最保守；1.8 = 下限价的社交/外卖场景）
UNIT_PER_ORDER_BAND = (1.0, 1.8)

# CSV 的「品牌」列名与 BRAND_KEYWORDS 的归一名可能不一致：
#   CSV 用「奈雪的茶」，关键词归一到「奈雪」；CSV 用「CoCo都可」，归一「CoCo」。
# 没有这张别名表时那一行**永远取不到**——旧实现就踩了这个坑：
# 传 '奈雪的茶(天一广场店)' → 归一成 '奈雪' → '奈雪' 不在 metrics；
# 再拿整个店名去比也不在 → 返回 None，于是奈雪的公开行形同不存在。
_METRIC_ALIASES = {'奈雪': '奈雪的茶', 'CoCo': 'CoCo都可'}

_BRAND_STORE_METRICS = None


def _load_store_metrics():
    """惰性加载 brand_store_metrics.csv（公开披露数据）。失败返回空 dict，不抛异常。"""
    global _BRAND_STORE_METRICS
    if _BRAND_STORE_METRICS is None:
        import csv
        from pathlib import Path
        path = Path(__file__).resolve().parent / 'brand_store_metrics.csv'
        out = {}
        try:
            with open(path, encoding='utf-8-sig', newline='') as f:
                for row in csv.DictReader(f):
                    b = (row.get('品牌') or '').strip()
                    if b:
                        out[b] = row
        except Exception:
            out = {}
        _BRAND_STORE_METRICS = out
    return _BRAND_STORE_METRICS


def _num(v):
    try:
        f = float(str(v).strip())
        return f if f > 0 else None
    except Exception:
        return None


def brand_store_metrics(name_or_brand):
    """取品牌级公开经营数据（招股书/年报口径）。识别不出或无收录 → None。"""
    if not name_or_brand:
        return None
    s = str(name_or_brand).strip()
    metrics = _load_store_metrics()
    brand, _ = brand_attractiveness(s)
    key = None
    for cand in (brand, s, _METRIC_ALIASES.get(brand)):
        if cand and cand in metrics:
            key = cand
            break
    if not key:
        return None
    row = dict(metrics[key])
    row['品牌'] = key
    return row


def brand_order_value(name_or_brand):
    """品牌级「每单金额」（元/单），供替换品类画像客单价。

    优先级：
      1. 公开披露的「每单平均零售额」（蜜雪 ¥11.4 / 沪上阿姨 ¥25 / 茶百道 ¥16.69）
      2. 「单杯价 × UNIT_PER_ORDER」（蜜雪、沪上阿姨两点标定的换算，粗估）
      3. 都没有 → None（调用方回退到品类画像）

    ⚠️ `公开值` 这个标志（2026-09-18 细化）：CSV 新增「每单金额来源」列，
       区分**披露值**（招股书/年报直接给的每单金额）与**我方推导值**（如瑞幸
       由"全年 GMV ÷ 全年杯量"推出）。两者都能用，但**必须能分辨** ——
       否则一个推导数会被当成公司披露值报出去，答辩一问口径就穿。
       旧行没有该列 → 默认按「披露」读（与旧行为一致）。

    返回 dict(每单金额, 单杯价, 换算系数, 来源, 公开值, 金额来源, 口径) 或 None。
    ⚠️ 键名是 `公开值`(bool) 与 `金额来源`(str)，**不是** `是否公开值` ——
      调用方按错名字取值会拿到 None 而被当成"没有该字段"（静默错）。
    """
    m = brand_store_metrics(name_or_brand)
    if not m:
        return None
    source = f"{m.get('数据来源') or '公开披露'}（{m.get('期间') or '—'}）"
    ov = _num(m.get('每单平均金额元'))
    if ov:
        origin = (m.get('每单金额来源') or '披露').strip() or '披露'
        derived = origin == '推导'
        caliber = (f'**推导值**·每单平均金额 ¥{ov:g}'
                   f'（来源：{m.get("期间") or "—"}；非公司直接披露的每单金额，'
                   f'由公开数据换算，明细见数据来源）'
                   if derived else
                   f'公开披露·每单平均零售额 ¥{ov:g}（{m.get("期间") or "—"}）')
        return {'每单金额': ov, '单杯价': _num(m.get('单杯均价元')),
                '换算系数': None, '来源': source, '公开值': not derived,
                '金额来源': origin, '口径': caliber}
    cup = _num(m.get('单杯均价元'))
    if cup:
        est = round(cup * UNIT_PER_ORDER, 2)
        return {'每单金额': est, '单杯价': cup, '换算系数': UNIT_PER_ORDER,
                '来源': source, '公开值': False,
                '口径': (f'无公开每单金额，按「单杯价 ¥{cup:g} × 每单 {UNIT_PER_ORDER} 杯」'
                         f'换算 ≈ ¥{est:g}（每单杯数由蜜雪 1.70 / 沪上阿姨 1.79 两点估计，粗估）')}
    return None


