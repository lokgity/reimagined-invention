# 轻量 TF-IDF 检索（中文 2-gram，纯 Python）
# ---------------------------------------------------------------
def _tokenize(text: str):
    """中文按 2-gram 切分，英文/数字按词。"""
    text = re.sub(r'\s+', '', text.lower())
    tokens = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch.isascii() and (ch.isalnum()):
            j = i
            while j < len(text) and text[j].isascii() and text[j].isalnum():
                j += 1
            tokens.append(text[i:j])
            i = j
        else:
            if i + 1 < len(text):
                tokens.append(text[i:i + 2])
            tokens.append(ch)
            i += 1
    return tokens


class _Index:
    def __init__(self, docs):
        self.docs = docs
        self.doc_tokens = [_tokenize(d['title'] + '。' + d['text']) for d in docs]
        self.df = Counter()
        for toks in self.doc_tokens:
            for t in set(toks):
                self.df[t] += 1
        self.n = len(docs)

    def _tfidf(self, toks):
        tf = Counter(toks)
        vec = {}
        for t, c in tf.items():
            idf = math.log((self.n + 1) / (self.df.get(t, 0) + 1)) + 1
            vec[t] = c * idf
        return vec

    def search(self, query, top_k=3, min_score=0.11, tags=None):
        """检索。`tags` 给定时按专家分区过滤。

        ⚠️ 分区过滤的**关键设计约束**（2026-09-16）：必须"**全库算分、排序后过滤**"，
        不能"只对分区建索引再算分"。原因：
          ① TF-IDF 的 IDF 依赖文档集大小 `self.n` 与 `self.df` ——
             若按分区建索引，每个专家的 IDF 都不同 → 同一句话的得分尺度漂移；
          ② `min_score = 0.11` 是在**全局分布**上标定的（见 verify_knowledge_rag.py），
             per-分区算分会让这个阈值失去意义（实测标定的间隙只有 ~0.02 宽）。
        所以：打分永远用全局索引，tags 只在**排序之后**做筛选。
        代价是分区内命中数可能少于 top_k —— 这是**刻意的**：
        宁可少给，也不跨区混入（那正是"审计师被喂「奶茶店选址要点」"的老问题）。
        """
        # ⚠️ min_score 由 verify_knowledge_rag.py 标定：
        #    原值 0.05 太松——「今天宁波天气怎么样」会命中「样本稳健性」、
        #    「推荐一部好看的电影」会命中「商铺水电成本量级」，
        #    题外话遂被注入 free_chat 的 prompt，污染闲聊回答。
        #    标定方法：取"标注查询的真实命中最低分"与"题外话最高分"之间的间隙中点。
        #    该阈值两侧均有回归断言锁定；**改语料后必须重跑该脚本重新标定**
        #    （语料条数变化会改变 IDF 与全部得分）。
        qv = self._tfidf(_tokenize(query))
        qnorm = math.sqrt(sum(v * v for v in qv.values())) or 1.0
        scored = []
        for i, toks in enumerate(self.doc_tokens):
            dv = self._tfidf(toks)
            dnorm = math.sqrt(sum(v * v for v in dv.values())) or 1.0
            dot = sum(qv[t] * dv.get(t, 0.0) for t in qv)
            sim = dot / (qnorm * dnorm)
            if sim >= min_score:
                scored.append((sim, i))
        scored.sort(reverse=True)

        if tags:
            tagset = set(tags)
            scored = [(s, i) for s, i in scored
                      if tagset & set(self.docs[i].get('tags') or [])]

        return [(self.docs[i], round(s, 3)) for s, i in scored[:top_k]]


_INDEX = None


def _get_index():
    global _INDEX
    if _INDEX is None:
        _INDEX = _Index(KNOWLEDGE_BASE)
    return _INDEX


def retrieve(query: str, top_k: int = 3, tags=None):
    """检索最相关知识条目，返回 [(doc, score)]。

    `tags` 见 `_Index.search` 的说明：分区过滤，但算分始终用全局索引。
    """
    return _get_index().search(query, top_k=top_k, tags=tags)


def build_context(query: str, top_k: int = 3, tags=None) -> str:
    """生成可注入 prompt 的知识条目文本（不含标题头，由调用方加）; 无匹配返回空串。

    带 `source` 的条目会在正文后附「（来源：…）」，让 LLM 能归因、
    也让"这条不是我编的"在 prompt 层面可追溯（方案 B 的落点）。
    带 `url` 的条目（政策类）会把原文链接以 markdown 形式列出，
    让 LLM 能直接给出可点击链接、也能让用户点进原文。
    无 source 的条目保持原格式，不影响既有条目的注入文本。
    """
    hits = retrieve(query, top_k=top_k, tags=tags)
    if not hits:
        return ''
    lines = []
    for doc, _score in hits:
        line = f'◆ {doc["title"]}: {doc["text"]}'
        src = doc.get('source')
        if src:
            line += f'（来源：{src}）'
        urls = doc.get('url')
        if urls:
            line += '\n　原文链接：' + '、'.join(
                f'[{u["标题"]}]({u["链接"]})' for u in urls)
        elif doc.get('url_note'):
            line += f'\n　（{doc["url_note"]}）'
        lines.append(line)
    return '\n'.join(lines)


def policy_links(query: str, top_k: int = 3, tags=None):
    """抽政策类语料里**带 url 的原文链接**，去重后返回 [(标题, url)]。

    供「创业政策顾问」在回答后**确定性追加参考链接块**用 —— 不依赖 LLM
    是否把链接抄进回答，用户一定能点到原文。无 url 的条目（如实标"未找到
    稳定链接"的）不在其列，避免给一个不存在的链接。
    """
    hits = retrieve(query, top_k=top_k, tags=tags)
    seen, out = set(), []
    for doc, _score in hits:
        for u in doc.get('url') or []:
            if u.get('链接') and u['链接'] not in seen:
                seen.add(u['链接'])
                out.append((u['标题'], u['链接']))
    return out


