def _g(*path, default=None):
    """按路径取值：`_g('锚点', '逐店明细', '家数')`。任一层缺失返回 default。"""
    cur = _facts()
    for k in path:
        if not isinstance(cur, dict):
            return default
        cur = cur.get(k)
        if cur is None:
            return default
    return cur


